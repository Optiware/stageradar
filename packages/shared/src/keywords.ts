/** Applique par-dessus les valeurs par défaut les sections redéfinies dans les Réglages. */
export function mergeKeywords(surcharge: Partial<MotsCles> | null | undefined): MotsCles {
  if (!surcharge) return DEFAULT_KEYWORDS;
  return {
    domaines: { ...DEFAULT_KEYWORDS.domaines, ...surcharge.domaines },
    types: { ...DEFAULT_KEYWORDS.types, ...surcharge.types },
    hors_domaine: surcharge.hors_domaine ?? DEFAULT_KEYWORDS.hors_domaine,
    niveau_trop_eleve: surcharge.niveau_trop_eleve ?? DEFAULT_KEYWORDS.niveau_trop_eleve,
    niveau_accessible: surcharge.niveau_accessible ?? DEFAULT_KEYWORDS.niveau_accessible,
  };
}
